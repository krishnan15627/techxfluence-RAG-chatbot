"""
ingest_website.py - download public TechXfluence pages and save them as knowledge.

Usage (from the project folder, with the virtual environment active):
    python ingest_website.py                 # fetch all default pages
    python ingest_website.py --url https://www.techxfluence.com/about
    python ingest_website.py --add "Title" "Text you copied from the website" --source https://...

Output: data/website_content.txt   (same format the chatbot already reads)

Notes
-----
* Only PUBLIC pages are read. Nothing private is collected.
* If the website is JavaScript-heavy, some text may be missing. In that case copy the
  text by hand into data/company_knowledge.txt, or use the --add option above.
* Your hand-written file data/company_knowledge.txt is NEVER overwritten.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import requests
from bs4 import BeautifulSoup

DATA_DIR = Path(__file__).parent / "data"
OUTPUT_FILE = DATA_DIR / "website_content.txt"

PAGES = {
    "Homepage": "https://www.techxfluence.com/",
    "About Us": "https://www.techxfluence.com/about",
    "Tech Services": "https://www.techxfluence.com/Techservice",
    "Events": "https://www.techxfluence.com/events",
    "Membership": "https://www.techxfluence.com/membership",
    "Host an Event": "https://www.techxfluence.com/host",
    "Careers": "https://www.techxfluence.com/careers",
    "Contact": "https://www.techxfluence.com/contact",
}
HEADERS = {"User-Agent": "Mozilla/5.0 (TechXfluence-AI knowledge ingester; educational use)"}


def fetch_text(url: str) -> str:
    resp = requests.get(url, headers=HEADERS, timeout=20)
    resp.raise_for_status()
    soup = BeautifulSoup(resp.text, "html.parser")
    for tag in soup(["script", "style", "noscript", "svg", "iframe"]):
        tag.decompose()
    lines = []
    for el in soup.find_all(["h1", "h2", "h3", "h4", "p", "li", "td", "th", "a", "button"]):
        text = re.sub(r"\s+", " ", el.get_text(" ", strip=True))
        if len(text) > 2 and text not in lines[-3:]:
            lines.append(text)
    # remove consecutive/near duplicates while keeping order
    seen, clean = set(), []
    for line in lines:
        if line not in seen:
            seen.add(line)
            clean.append(line)
    return "\n".join(clean)


def build_section(title: str, url: str, text: str) -> str:
    return f"=== SECTION: {title} ===\nSOURCE: {url}\n{text}\n"


def ingest(pages: dict[str, str]) -> int:
    DATA_DIR.mkdir(exist_ok=True)
    sections, ok = [], 0
    for title, url in pages.items():
        try:
            text = fetch_text(url)
            if len(text) < 80:
                print(f"  [skip] {title}: very little text found (page may need JavaScript)")
                continue
            sections.append(build_section(f"Website - {title}", url, text))
            ok += 1
            print(f"  [ok]   {title}: {len(text)} characters")
        except requests.exceptions.RequestException as exc:
            print(f"  [fail] {title}: {exc}")
    if sections:
        header = "# Auto-generated by ingest_website.py - safe to delete and regenerate.\n\n"
        OUTPUT_FILE.write_text(header + "\n".join(sections), encoding="utf-8")
        print(f"\nSaved {ok} page(s) to {OUTPUT_FILE}")
    else:
        print("\nNothing saved. Check your internet connection or add content manually (see --add).")
    return ok


def add_manual(title: str, text: str, source: str) -> None:
    """Append hand-collected content to data/manual_content.txt."""
    DATA_DIR.mkdir(exist_ok=True)
    manual = DATA_DIR / "manual_content.txt"
    with manual.open("a", encoding="utf-8") as f:
        f.write("\n" + build_section(title, source, text.strip()))
    print(f"Added '{title}' to {manual}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Collect TechXfluence website content for the chatbot.")
    parser.add_argument("--url", help="fetch only this single URL")
    parser.add_argument("--add", nargs=2, metavar=("TITLE", "TEXT"), help="manually add a section")
    parser.add_argument("--source", default="https://www.techxfluence.com/", help="source link for --add")
    args = parser.parse_args()

    if args.add:
        add_manual(args.add[0], args.add[1], args.source)
    elif args.url:
        ingest({"Custom page": args.url})
    else:
        print("Fetching TechXfluence website pages...")
        sys.exit(0 if ingest(PAGES) else 1)


if __name__ == "__main__":
    main()
